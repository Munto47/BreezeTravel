"""Create source-disjoint train/validation/blind retrieval cases from public records.

Question text is deterministic and intentionally modest: it tests whether the
retriever returns the source containing the requested fact, not an LLM's skill
at inventing a plausible answer.  A run cannot be published when fewer than
three independent source records exist for any city.
"""

import argparse
import hashlib
import json
import re
from collections import defaultdict
from pathlib import Path


SPLITS = ("train", "validation", "blind")
QUESTIONS_PER_SOURCE = 20


def _sentences(content: str) -> list[str]:
    return [part.strip() for part in re.split(r"(?<=[。.!?])\s+", content) if len(part.strip()) >= 30]


def build_cases(records: list[dict]) -> dict:
    by_city: dict[str, list[dict]] = defaultdict(list)
    for record in records:
        if record.get("corpus_kind") != "public":
            raise ValueError("evaluation accepts only public corpus records")
        by_city[record["city"]].append(record)
    cases: list[dict] = []
    counts: dict[str, dict[str, int]] = {}
    for city, city_records in sorted(by_city.items()):
        if len(city_records) < 3:
            raise ValueError(f"{city} needs at least three source records for source-disjoint splits")
        counts[city] = {split: 0 for split in SPLITS}
        ordered = sorted(city_records, key=lambda item: hashlib.sha256(item["id"].encode()).hexdigest())
        for index, record in enumerate(ordered):
            split = SPLITS[index % len(SPLITS)]
            facts = _sentences(record["content"]) or [record["content"]]
            for question_index in range(QUESTIONS_PER_SOURCE):
                fact = facts[question_index % len(facts)]
                cases.append({
                    "id": f"{record['id']}-q{question_index + 1:02d}", "split": split, "city": city,
                    # The fact itself is the deterministic Chinese retrieval
                    # query.  It is not an answer generated by an LLM: this
                    # measures whether the public corpus can recover the page
                    # that contains a known atomic fact.
                    "question": f"{city}行前信息检索：{fact}",
                    "expected_source_id": record["id"], "answer_key": fact[:320],
                    "source_revision": record["source_revision"],
                })
                counts[city][split] += 1
        if counts[city]["blind"] < QUESTIONS_PER_SOURCE:
            raise ValueError(f"{city} blind split is below {QUESTIONS_PER_SOURCE}")
    return {"schema_version": "1.0", "split_policy": "source-disjoint", "counts": counts, "cases": cases}


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--input", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    records = [json.loads(line) for line in args.input.read_text(encoding="utf-8").splitlines() if line.strip()]
    result = build_cases(records)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(result, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
