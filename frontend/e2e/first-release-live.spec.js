const {test,expect}=require('@playwright/test')
const {randomUUID}=require('node:crypto')

const pageErrors=new WeakMap()
test.beforeEach(async({page})=>{
 pageErrors.set(page,[])
 page.on('pageerror',e=>pageErrors.get(page).push(e.name+': '+e.message.replace(/https?:\/\/\S+/g,'[url]')))
})
test.afterEach(async({page})=>{expect(pageErrors.get(page)).toEqual([])})

async function register(page,nickname) {
 await page.getByRole('button',{name:'注册账号',exact:true}).click()
 await page.getByLabel('邮箱',{exact:true}).fill(`release-${randomUUID()}@example.test`)
 await page.getByLabel('密码',{exact:true}).fill(`Test${randomUUID()}9`)
 await page.getByLabel('称呼（选填）',{exact:true}).fill(nickname)
 await page.getByRole('button',{name:'注册并继续',exact:true}).click()
}

