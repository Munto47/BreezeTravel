test('real collaboration: two accounts join, AI places synchronize, explicit driving, save and transfer',async({page,browser},info)=>{
 let optimization=0
 page.on('request',r=>{if(r.method()==='POST'&&new URL(r.url()).pathname.endsWith('/optimize'))optimization++})
 await page.goto('/collaborate')
 await expect(page).toHaveURL(/\/login$/)
 await register(page,'协同测试甲')
 await expect(page).toHaveURL(/\/collaborate$/,{timeout:30000})
 await page.getByLabel('目的地（选填）').fill('北京')
 await page.getByLabel('行程天数').selectOption('1')
 await page.getByRole('button',{name:'创建协同房间',exact:true}).click()
 await expect(page).toHaveURL(/\/room\/[^/?#]+$/,{timeout:30000})
 const roomUrl=page.url(),roomId=new URL(roomUrl).pathname.split('/').pop()
 await expect(page.getByTestId('chat-input')).toBeVisible()
 const second=await browser.newContext()
 try {
  const peer=await second.newPage()
  peer.on('pageerror',e=>pageErrors.get(page).push('peer: '+e.name))
  await peer.goto(new URL('/collaborate',roomUrl).href)
  await register(peer,'协同测试乙')
  await expect(peer.getByLabel('房间号')).toBeVisible({timeout:30000})
  await peer.getByLabel('房间号').fill(roomId)
  await peer.getByRole('button',{name:'加入协同房间',exact:true}).click()
  await expect(peer).toHaveURL(roomUrl,{timeout:30000})
  // Room's real initial AI request supplies provider-verified candidates.
  for(const tab of ['美景','美食','美梦']) {
   await page.getByRole('button',{name:new RegExp(tab)}).first().click()
   const choice=page.locator('[data-place-id]').filter({has:page.getByText(({'美景':'🏛 景点','美食':'🍜 美食','美梦':'🏨 住宿'})[tab],{exact:true})}).getByRole('button',{name:/^选择 /}).first()
   await expect.poll(async()=>await choice.count()>0||await page.getByText('暂时无法完成，请稍后重试。',{exact:true}).count()>0,{timeout:120000}).toBe(true)
   await expect(choice).toBeVisible()
   const selectedName=(await choice.getAttribute('aria-label')).replace(/^选择 /,'')
   await page.getByRole('button',{name:`选择 ${selectedName}`,exact:true}).click()
   await expect(page.getByRole('button',{name:`取消选择 ${selectedName}`,exact:true})).toBeVisible()
   console.log('Shared selection category:',tab)
   await peer.getByRole('button',{name:new RegExp(tab)}).first().click()
   await expect(peer.getByRole('button',{name:`取消选择 ${selectedName}`,exact:true})).toBeVisible({timeout:30000})
  }
  expect(optimization).toBe(0)
  const chat=page.getByTestId('chat-input')
  await chat.fill('这些地点中，第一次来北京可以优先选哪一处？请简短回答。')
  await expect(page.getByTestId('chat-send')).toBeEnabled({timeout:45000})
  const chatDone=page.waitForResponse(r=>new URL(r.url()).pathname==='/api/chat'&&r.request().method()==='POST')
  await page.getByTestId('chat-send').click()
  const chatResponse=await chatDone
  expect(chatResponse.status()).toBe(200)
  await chat.fill('保留为未发送的草稿')
  await expect(page.getByTestId('chat-send')).toBeEnabled({timeout:45000})
  await expect(page.locator('.rounded-tl-md')).toHaveCount(2)
  await expect(page.locator('.rounded-tl-md').last()).not.toBeEmpty()
  await expect(page.getByText('暂时无法完成，请稍后重试。',{exact:true})).toHaveCount(0)
  await chat.clear()
  await page.getByRole('button',{name:/智能排线/}).click()
  await expect.poll(()=>optimization,{timeout:90000}).toBe(1)
  await expect(page.getByRole('button',{name:'转入行程查',exact:true})).toBeEnabled({timeout:120000})
  await page.screenshot({path:info.outputPath('collaboration-saved.png'),fullPage:true})
  await page.reload()
  await expect(page.getByRole('button',{name:'转入行程查',exact:true})).toBeEnabled({timeout:30000})
  expect(optimization).toBe(1)
  await page.getByRole('button',{name:'转入行程查',exact:true}).click()
  await expect(page.getByTestId('itinerary-workspace')).toBeVisible({timeout:120000})
  await expect(page.getByRole('button',{name:'已保存到账号',exact:true})).toBeVisible()
  expect(await page.getByTestId('activity-card').count()).toBeGreaterThan(0)
  await peer.reload()
  await expect(peer.getByTestId('chat-input')).toBeVisible({timeout:30000})
 } finally {await second.close()}
})

